/**
 * Normaliza a string do acorde removendo baixos invertidos ou caracteres especiais
 * para busca no banco de digitações.
 */
export function cleanChordName(chord: string): string {
  const slashParts = chord.split('/');
  return slashParts[0].trim();
}

/**
 * Retorna todas as formas (variações) cadastradas para o acorde e instrumento.
 */
export function getAllChordShapes(chord: string, instrument: InstrumentType): ChordShape[] {
  const clean = cleanChordName(chord);
  const db = instrument === 'cavaco' ? CAVACO_CHORD_DB : VIOLAO_CHORD_DB;

  let shapesFrets = db[clean];

  if (!shapesFrets || shapesFrets.length === 0) {
    // Tentar fallback simplificando sufixo (ex: C9 -> C7 -> C)
    const baseMatch = clean.match(/^([A-G][#b]?)(m?)/);
    if (baseMatch) {
      const fallback = baseMatch[1] + (baseMatch[2] || '');
      shapesFrets = db[fallback];
    }
  }

  // Se ainda não encontrado, formato neutro
  if (!shapesFrets || shapesFrets.length === 0) {
    shapesFrets = [instrument === 'cavaco' ? [0, 0, 0, 0] : [0, 2, 2, 0, 0, 0]];
  }

  const total = shapesFrets.length;
  return shapesFrets.map((frets, idx) => ({
    chord,
    instrument,
    frets,
    variationIndex: idx,
    totalVariations: total
  }));
}

/**
 * Retorna o desenho do acorde (posições de trastes) para o instrumento escolhido,
 * respeitando o índice da variação solicitada (0 para Forma 1, 1 para Forma 2, etc.)
 */
export function getChordShape(chord: string, instrument: InstrumentType, variationIndex: number = 0): ChordShape {
  const shapes = getAllChordShapes(chord, instrument);
  const safeIdx = ((variationIndex % shapes.length) + shapes.length) % shapes.length;
  return shapes[safeIdx];
}
